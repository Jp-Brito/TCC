// Leitor de CSV simples, usado nos arquivos do GTFS (routes.txt, stops.txt...).
// Aceita campos entre aspas, inclusive com vírgulas e aspas duplas dentro.
// Devolve uma lista de linhas, cada linha é uma lista de campos.
export function lerCsv(texto) {
  const linhas = [];
  let campo = "", linha = [], entreAspas = false;
  for (let i = 0; i < texto.length; i++) {
    const c = texto[i];
    if (entreAspas) {
      if (c === '"' && texto[i + 1] === '"') { campo += '"'; i++; }
      else if (c === '"') entreAspas = false;
      else campo += c;
    } else if (c === '"') entreAspas = true;
    else if (c === ",") { linha.push(campo); campo = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && texto[i + 1] === "\n") i++;
      linha.push(campo); campo = "";
      if (linha.length > 1 || linha[0] !== "") linhas.push(linha);
      linha = [];
    } else campo += c;
  }
  if (campo !== "" || linha.length) { linha.push(campo); linhas.push(linha); }
  return linhas;
}
